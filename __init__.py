"""approval-notifier — never miss or misread an approval prompt again.

v1.0.0: two-stage alerts with plain-language Chinese command explanations.

Scenario: the user backgrounds the terminal running Hermes. When a
dangerous-command approval prompt appears, they (a) may not see it
(60s default auto-deny) and (b) can't read raw shell syntax anyway.

Behavior now, in two stages:
- Stage 1 (immediate): Windows Toast with the risk category translated
  to Chinese via a static table (deterministic, zero latency, no LLM),
  plus the raw command. Alarm tone + console beeps start immediately
  and repeat every 15s until the approval is resolved.
- Stage 2 (a few seconds later, async): a second Toast titled
  「命令解读」 generated by the user's ACTIVE main model (via
  agent.auxiliary_client.call_llm with config.yaml's model section,
  read fresh per call so model switches are honored): one line saying
  what the command concretely does, one line with a risk verdict. If
  the LLM fails/times out, stage 2 is silently skipped — stage 1
  already fired.

The approval decision itself still happens in the terminal (y/n); the
toasts are observers only. Never blocks the agent thread.
"""

import base64
import logging
import subprocess
import sys
import threading
import time
from xml.sax.saxutils import escape

logger = logging.getLogger(__name__)

_BELL_INTERVAL_S = 15.0        # repeating beep interval
_BELL_MAX_S = 900.0            # hard stop: 15 minutes of beeping max
_LLM_TIMEOUT_S = 25.0          # stage-2 explanation budget
_LLM_MAX_INPUT_CHARS = 2000    # truncate huge commands before the LLM
_AUMID = ("{1AC14E77-02E7-4E5D-B744-2EB1AE5198B7}"
          r"\WindowsPowerShell\v1.0\powershell.exe")

_stop = threading.Event()
_gen = 0                       # request generation counter
_gen_lock = threading.Lock()
_ctx = None                    # plugin ctx (saved at register()) for ctx.llm

