def _is_windows() -> bool:
    return sys.platform.startswith("win")


def _cn_reason(description: str) -> str:
    """Translate a '; '-joined English rule description to Chinese."""
    if not description:
        return "危险命令"
    parts = [p.strip() for p in description.split(";") if p.strip()]
    return " + ".join(_DESC_CN.get(p, p) for p in parts)


def _beep_triple():
    """One alarm burst: three rising tones (~0.8s total)."""
    try:
        import winsound
        for freq in (2093, 2093, 2637):
            winsound.Beep(freq, 180)
    except Exception:
        try:
            print("\a" * 3, end="", flush=True)
        except Exception:
            pass


def _send_toast(title: str, body: str, *, alarm: bool = True) -> None:
    """Pop a Windows Toast. Title/body are XML-escaped (v0.2 fix: command
    text can contain < & etc. which previously broke the toast XML).

    XML goes to PowerShell base64-encoded so arbitrary command text can
    never break quoting. Fire-and-forget subprocess: a hung PowerShell can
    not block Hermes.
    """
    body = (body or "").strip()
    if len(body) > 300:
        body = body[:297] + "..."
    audio = ('<audio src="ms-winsoundevent:Notification.Looping.Alarm"/>'
             if alarm else "")
    xml = (
        '<toast scenario="reminder">'
        '<visual><binding template="ToastGeneric">'
        f"<text>{escape(title)}</text>"
        f"<text>{escape(body)}</text>"
        "</binding></visual>"
        f"{audio}"
        "</toast>"
    )
    b64 = base64.b64encode(xml.encode("utf-8")).decode("ascii")
    ps = (
        "$ErrorActionPreference='SilentlyContinue';"
        "[Windows.UI.Notifications.ToastNotificationManager,"
        "Windows.UI.Notifications,ContentType=WindowsRuntime]|Out-Null;"
        "[Windows.Data.Xml.Dom.XmlDocument,"
        "Windows.Data.Xml.Dom.XmlDocument,ContentType=WindowsRuntime]|Out-Null;"
        f"$x=[Text.Encoding]::UTF8.GetString([Convert]::FromBase64String('{b64}'));"
        "$doc=New-Object Windows.Data.Xml.Dom.XmlDocument;"
        "$doc.LoadXml($x);"
        "$t=New-Object Windows.UI.Notifications.ToastNotification($doc);"
        f"[Windows.UI.Notifications.ToastNotificationManager]::CreateToastNotifier('{_AUMID}').Show($t)"
    )
    encoded = base64.b64encode(ps.encode("utf-16-le")).decode("ascii")
    subprocess.Popen(
        ["powershell.exe", "-NoProfile", "-NonInteractive",
         "-WindowStyle", "Hidden", "-EncodedCommand", encoded],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        creationflags=(0x08000000 if _is_windows() else 0),  # CREATE_NO_WINDOW
    )


# ------------------------------------------------------------------
# Stage 2: LLM-generated Chinese explanation
# ------------------------------------------------------------------

def _explain_command(command: str, reason_cn: str):
    """Ask the user's active main model for a 2-line Chinese explanation.

    Calls agent.auxiliary_client.call_llm directly with the model section
    read fresh from config (so model switches are picked up). Deliberately
    NOT ctx.llm/PluginLlm: with task=None its "auto" chain misroutes to a
    relay that rejects the key (401 Invalid api_key format, verified
    2026-09-12). Returns (action_line, risk_line) or None on any failure.
    """
    try:
        from hermes_cli.config import load_config
        from agent.auxiliary_client import call_llm
        m = (load_config() or {}).get("model", {}) or {}
        if not (m.get("base_url") and m.get("api_key") and m.get("default")):
            return None
        prompt = (
            "你是中文安全助手,服务对象是不懂命令行的用户。下面这条终端命令被 Hermes "
            f"审批拦截,标记原因:{reason_cn}。\n\n命令:\n{command[:_LLM_MAX_INPUT_CHARS]}\n\n"
            "请严格按以下格式回复两行,不要任何其他文字、不要代码块:\n"
            "做什么: <一句中文,不超过45字,说明具体操作对象和路径>\n"
            "风险: <高危|中危|低危>。<一句中文,不超过45字,说明批准后可能的后果>"
        )
        response = call_llm(
            task=None,
            model=m.get("default"),
            base_url=m.get("base_url"),
            api_key=m.get("api_key"),
            messages=[{"role": "user", "content": prompt}],
            temperature=0.2, max_tokens=700, timeout=_LLM_TIMEOUT_S,
        )
        text = ""
        try:
            text = response.choices[0].message.content or ""
        except Exception:
            pass
        # reasoning models wrap output in <think>...</think>
        if "</think>" in text:
            text = text.split("</think>")[-1]
        lines = [l.strip() for l in text.splitlines() if l.strip()]
        action = next((l for l in lines if l.startswith("做什么")), "")
        risk = next((l for l in lines if l.startswith("风险")), "")
        if not action and len(lines) >= 2:
            action, risk = lines[0], lines[1]
        if not action and not risk:
            return None
        return (action or "做什么: (模型未说明)", risk or "风险: (模型未评级)")
    except Exception as exc:
        logger.debug("approval-notifier: LLM explain failed: %s", exc)
        return None


def _explain_worker(command: str, reason_cn: str, my_gen: int):
    """Stage-2 thread: generate explanation, toast it IF the approval is
    still pending and this is still the latest request."""
    try:
        pair = _explain_command(command, reason_cn)
        if pair is None:
            return
        if _stop.is_set():
            return                     # already resolved — don't spam
        with _gen_lock:
            if _gen != my_gen:
                return                 # a newer approval superseded this one
        _send_toast("📖 Hermes 命令解读",
                    f"{pair[0]}\n{pair[1]}", alarm=False)
    except Exception as exc:
        logger.debug("approval-notifier: explain worker failed: %s", exc)


def _alert_worker(command: str, reason_cn: str, my_gen: int):
    """Stage-1: immediate toast + beeps, then repeating beeps until resolved."""
    try:
        _send_toast("⏰ Hermes 审批请求", f"⚠ {reason_cn}\n命令: {command}")
    except Exception as exc:
        logger.debug("approval-notifier toast failed: %s", exc)
    try:
        _beep_triple()
    except Exception:
        pass
    # Stage 2 runs in its own thread so a slow LLM never delays the alarm.
    threading.Thread(target=_explain_worker, args=(command, reason_cn, my_gen),
                     daemon=True).start()
    deadline = time.time() + _BELL_MAX_S
    while not _stop.wait(_BELL_INTERVAL_S):
        if time.time() >= deadline:
            break
        try:
            _beep_triple()
        except Exception:
            break


def on_pre_approval_request(**kwargs):
    """pre_approval_request hook: alarm now, Chinese explanation async."""
    command = kwargs.get("command", "") or ""
    description = kwargs.get("description", "") or ""
    surface = kwargs.get("surface", "")
    reason_cn = _cn_reason(description)
    logger.info("approval-notifier: approval requested (surface=%s, %s)",
                surface, reason_cn)
    _stop.clear()
    with _gen_lock:
        global _gen
        _gen += 1
        my_gen = _gen
    threading.Thread(target=_alert_worker,
                     args=(command, reason_cn, my_gen), daemon=True).start()


def on_post_approval_response(**kwargs):
    """post_approval_response hook: stop the alarm, suppress pending stage-2."""
    _stop.set()


def register(ctx):
    global _ctx
    _ctx = ctx
    ctx.register_hook("pre_approval_request", on_pre_approval_request)
    ctx.register_hook("post_approval_response", on_post_approval_response)
